CREATE TABLE IF NOT EXISTS video_intake (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url TEXT UNIQUE NOT NULL,
    created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"')
);
CREATE TABLE IF NOT EXISTS video_processing (
    video_id BIGINT PRIMARY KEY REFERENCES video_intake(id),
    state TEXT NOT NULL, detail TEXT NOT NULL DEFAULT '', transcript_path TEXT, method TEXT
);
CREATE TABLE IF NOT EXISTS video_metadata (
    video_id BIGINT PRIMARY KEY REFERENCES video_intake(id), data JSONB NOT NULL
);
CREATE TABLE IF NOT EXISTS transcript_versions (
    video_id BIGINT NOT NULL REFERENCES video_intake(id), kind TEXT NOT NULL,
    path TEXT NOT NULL, method TEXT NOT NULL, PRIMARY KEY(video_id,kind)
);
CREATE TABLE IF NOT EXISTS caption_checks (
    video_id BIGINT PRIMARY KEY REFERENCES video_intake(id), status TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS study_runs (
    video_id BIGINT NOT NULL REFERENCES video_intake(id), model TEXT NOT NULL,
    data JSONB NOT NULL, PRIMARY KEY(video_id,model)
);
CREATE TABLE IF NOT EXISTS study_run_history (
    video_id BIGINT NOT NULL REFERENCES video_intake(id), model TEXT NOT NULL,
    run_number INTEGER NOT NULL, data JSONB NOT NULL, PRIMARY KEY(video_id,model,run_number)
);
